// Generates the app theme from the approved SHR-105 tokens (docs/design/tokens/atepdf-tokens.json).
// Outputs: the Uniwind theme stylesheet (light + dark CSS variables) and a typed token module
// for values React Native styles need directly (type scale, elevation, sizes, motion).
// `--check` fails when either output is stale, so the JSON stays the single source of truth.
import {readFile,writeFile} from 'node:fs/promises';

const check=process.argv.includes('--check');
const tokens=JSON.parse(await readFile('docs/design/tokens/atepdf-tokens.json','utf8'));

// Token name → Tailwind colour name. Every colour token is mapped; an unmapped one fails.
const colorNames={
  'bg.window':'window','bg.sunken':'sunken','bg.panel':'panel',
  'surface.raised':'raised','surface.elevated':'elevated','surface.request':'request',
  'surface.hover':'hover','surface.pressed':'pressed','surface.selected':'selected',
  'border.hairline':'hairline','border.strong':'strong',
  'text.primary':'ink','text.secondary':'ink-secondary','text.tertiary':'ink-tertiary','text.disabled':'ink-disabled','text.onAccent':'on-accent',
  'accent.fill':'accent','accent.fillHover':'accent-hover','accent.fillPressed':'accent-pressed','accent.text':'accent-text','accent.subtle':'accent-subtle','accent.subtleBorder':'accent-border',
  'status.success.fg':'success','status.warning.fg':'warning','status.warning.bg':'warning-bg',
  'status.danger.fg':'danger','status.danger.bg':'danger-bg','status.danger.fill':'danger-fill',
  'status.local.fg':'local','status.local.bg':'local-bg','status.outbound.fg':'outbound','status.outbound.bg':'outbound-bg',
  'page.paper':'paper','scrim':'scrim','dropzone.fill':'dropzone',
};
for(const scheme of ['light','dark'])for(const name of Object.keys(tokens.color[scheme]))if(!colorNames[name])throw new Error(`Unmapped colour token ${name}`);

const header='/* Generated by scripts/design-tokens.mjs from docs/design/tokens/atepdf-tokens.json. Do not edit. */\n';
const variables=scheme=>Object.entries(tokens.color[scheme]).map(([name,value])=>`      --color-${colorNames[name]}: ${value};`).join('\n');
const css=`${header}@layer theme {
  :root {
    @variant light {
${variables('light')}
    }
    @variant dark {
${variables('dark')}
    }
  }
}
`;

const type=Object.fromEntries(Object.entries(tokens.type).map(([name,t])=>[name,{fontSize:t.size,lineHeight:t.line,fontWeight:String(t.weight),letterSpacing:t.tracking}]));
const pair=value=>Array.isArray(value)?{width:value[0],height:value[1]}:value;
const size=Object.fromEntries(Object.entries(tokens.size).map(([name,value])=>[name,pair(value)]));
// TypeScript keys are the Tailwind names in camelCase (ink-secondary → inkSecondary).
const camel=name=>name.replace(/-([a-z])/g,(_,letter)=>letter.toUpperCase());
const colors=scheme=>Object.fromEntries(Object.entries(tokens.color[scheme]).map(([name,value])=>[camel(colorNames[name]),value]));
const ts=`${header.replace('/*','//').replace(' */','')}
export const typeScale=${JSON.stringify(type,null,2)} as const;
export const space=${JSON.stringify(tokens.space,null,2)} as const;
export const radius=${JSON.stringify(tokens.radius,null,2)} as const;
export const size=${JSON.stringify(size,null,2)} as const;
export const elevation=${JSON.stringify(tokens.elevation,null,2)} as const;
export const motion=${JSON.stringify(Object.fromEntries(Object.entries(tokens.motion).filter(([name])=>name!=='reduced')),null,2)} as const;
export const layer=${JSON.stringify(tokens.layer,null,2)} as const;
export const colors={light:${JSON.stringify(colors('light'),null,2)},dark:${JSON.stringify(colors('dark'),null,2)}} as const;
export type TypeRole=keyof typeof typeScale;
export type ColorName=keyof typeof colors.light;
`;

for(const [path,content] of [['apps/universal/src/ui/theme/theme.css',css],['apps/universal/src/ui/theme/tokens.ts',ts]]){
  if(check){if(await readFile(path,'utf8').catch(()=>null)!==content)throw new Error(`Generated theme is stale: ${path}. Run node scripts/design-tokens.mjs.`);}
  else await writeFile(path,content);
}
console.log(check?'Theme matches the approved design tokens.':'Theme generated from the approved design tokens.');
